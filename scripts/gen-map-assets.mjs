import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(scriptDir, '../src/modules/game/core/assets/maps');
const maps = ['01-sunny-meadow', '02-woodland-trail', '03-lakeside-retreat'];

for (const id of maps) {
  const mapDir = path.join(root, id);
  const manifest = JSON.parse(fs.readFileSync(path.join(mapDir, 'manifest.json'), 'utf8'));
  const camelId = id.replace(/^\d+-/, '').replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

  const propEntries = manifest.props.map(
    (p) => `  '${p.id}': require('./${id}/props/${path.basename(p.file)}'),`
  ).join('\n');

  const out = `// AUTO-GENERATED by scripts/gen-map-assets — do not hand-edit. Re-run after asset changes.
import layout from './${id}/map/layout.json';

export const groundImage = require('./${id}/map/ground.png');
export const waterFullMapFrames = [
  require('./${id}/animations/water/full-map/frame-00.png'),
  require('./${id}/animations/water/full-map/frame-01.png'),
  require('./${id}/animations/water/full-map/frame-02.png'),
  require('./${id}/animations/water/full-map/frame-03.png'),
  require('./${id}/animations/water/full-map/frame-04.png'),
  require('./${id}/animations/water/full-map/frame-05.png'),
  require('./${id}/animations/water/full-map/frame-06.png'),
  require('./${id}/animations/water/full-map/frame-07.png'),
];
export const grassSheet = require('./${id}/animations/grass/sheet.png');
export const reedsSheet = require('./${id}/animations/reeds/sheet.png');

export const propImages: Record<string, number> = {
${propEntries}
};

export const mapManifest = ${JSON.stringify(manifest, null, 2)};
export const mapLayout = layout;
`;

  fs.writeFileSync(path.join(root, `${camelId}.ts`), out);
  console.log('wrote', camelId + '.ts');
}
