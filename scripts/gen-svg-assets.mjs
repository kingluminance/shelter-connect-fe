import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

// Inlines <module>/assets/svg/*.svg (exported from Figma) as XML strings for
// react-native-svg's SvgXml — avoids a metro svg-transformer dependency.
// Add a module's assets dir to `targets` to generate its svgAssets.ts.
const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const targets = ['../src/modules/home/assets', '../src/modules/dog/assets'];

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

for (const target of targets) {
  const dir = path.join(scriptDir, target);
  const svgDir = path.join(dir, 'svg');
  const entries = fs
    .readdirSync(svgDir)
    .filter((f) => f.endsWith('.svg'))
    .sort()
    .map((f) => {
      const xml = fs
        .readFileSync(path.join(svgDir, f), 'utf8')
        .replace(/ style="display: block;"/, '')
        .replace(/ id="(?!clip)[^"]*"/g, '')
        .replace(/\s*\n\s*/g, '');
      return `  ${camel(path.basename(f, '.svg'))}: ${JSON.stringify(xml)},`;
    });

  fs.writeFileSync(
    path.join(dir, 'svgAssets.ts'),
    `// AUTO-GENERATED by scripts/gen-svg-assets.mjs from ./svg/*.svg — do not hand-edit.\nexport const svgAssets = {\n${entries.join('\n')}\n} as const;\n`,
  );
  console.log(`${target}: wrote ${entries.length} svgs`);
}
