// Builds tools/game-tuner/data.js from the game's real source values, so the tuner opens with exactly what the
// app uses today. Re-run after the constants / layout.json change:  npm run tuner
import { readFileSync, writeFileSync } from 'node:fs';

const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const game = read('src/modules/game/GameScreen.tsx');
const dogSm = read('src/modules/game/core/systems/dogStateMachine.ts');
const ball = read('src/modules/game/core/systems/ballPlay.ts');
const MAP = 'src/modules/game/core/assets/maps/01-sunny-meadow';
const layout = JSON.parse(read(`${MAP}/map/layout.json`));

function num(source, name, fallback) {
  const match = source.match(new RegExp(`const ${name} = ([0-9.]+)`));
  return match ? Number(match[1]) : fallback;
}
const ratio = (source, name, fallback) => {
  const match = source.match(new RegExp(`const ${name} = DOG_DISPLAY_SIZE \\* ([0-9.]+)`));
  return match ? Number(match[1]) : fallback;
};

const offset = game.match(/const PLAYER_SPRITE_OFFSET = \{ x: (-?[0-9.]+), y: (-?[0-9.]+) \}/);

const constants = {
  playerSpriteOffsetX: offset ? Number(offset[1]) : 0,
  playerSpriteOffsetY: offset ? Number(offset[2]) : 0,
  dogDisplaySize: num(game, 'DOG_DISPLAY_SIZE', 44),
  dogCollisionRadiusRatio: ratio(game, 'DOG_COLLISION_RADIUS', 0.18),
  dogCollisionYOffsetRatio: ratio(game, 'DOG_COLLISION_Y_OFFSET', 0.85),
  playerDisplaySize: num(game, 'PLAYER_DISPLAY_SIZE', 64),
  playerRadius: num(game, 'PLAYER_RADIUS', 10),
  talkRange: num(game, 'TALK_RANGE', 40),
  dogRadius: num(dogSm, 'DOG_RADIUS', 8),
  engageDistance: num(ball, 'ENGAGE_DISTANCE', 75),
  receiveDistance: num(ball, 'RECEIVE_DISTANCE', 58),
  throwRange: num(ball, 'THROW_RANGE', 76),
  leaveDistance: num(ball, 'LEAVE_DISTANCE', 120),
  playerSpeed: num(game, 'PLAYER_SPEED', 55),
  runMultiplier: num(game, 'RUN_MULTIPLIER', 1.8),
  viewportMapUnits: num(game, 'VIEWPORT_MAP_UNITS', 200),
};

const A = '../../src/modules/game/core/assets';
const data = {
  generatedAt: new Date().toISOString(),
  layout,
  constants,
  assets: {
    ground: `${A}/maps/01-sunny-meadow/map/ground.png`,
    propDir: `${A}/maps/01-sunny-meadow/props/`,
    dogDown: `${A}/dog/real-map-v1/idle-south.png`,
    dogUp: `${A}/dog/real-map-v1/idle-north.png`,
    dogSide: `${A}/dog/real-v1/sheets/idle.png`,
    player: `${A}/character/player-walk.png`,
  },
};
writeFileSync(new URL('../tools/game-tuner/data.js', import.meta.url), `// generated by scripts/gen-game-tuner-data.mjs — do not edit\nwindow.TUNER_DATA = ${JSON.stringify(data)};\n`);
console.log('tools/game-tuner/data.js written —', layout.obstacles.length, 'obstacles,', layout.objects.length, 'props');
